ALTER PROCEDURE [dbo].[DISP_PO_AUTO_MAP]
    @SCHEDULE_SRNOS NVARCHAR(MAX),
    @USER_SRNO INT
AS
BEGIN
-- Create a temporary table to hold the schedule serial numbers
    DECLARE @TempScheduleSrnos TABLE (SCHEDULE_SRNO INT);
    
    -- Parse the comma-separated list of SCHEDULE_SRNOS
    INSERT INTO @TempScheduleSrnos (SCHEDULE_SRNO)
    SELECT value FROM STRING_SPLIT(@SCHEDULE_SRNOS, ',');
    
    -- Group POs by thickness, grade, and OD
    SELECT 
        G.GRADE,
        G.GRADE_SRNO,
        T.THICKNESS,
        T.THICKNESS_SRNO,
        O.OD,
        O.OD_SRNO,
        SM.ITEM_TYPE,
		SM.PARTY_NAME,
		SM.PO_NUMBER,
		SUM(CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN ISNULL(SD.QUANTITY, 0) ELSE 0 END) AS PIPE_QTY,
        SUM(CASE WHEN SM.ITEM_TYPE IN ('COIL', 'SHEET') THEN ISNULL(SD.WEIGHT_KG, 0) ELSE 0 END) AS COIL_SHEET_WEIGHT,
        STRING_AGG(CAST(SM.SCHEDULE_SRNO AS VARCHAR), ',') AS SCHEDULE_SRNOS,
        STRING_AGG(CAST(SD.SCHEDULE_DT_SRNO AS VARCHAR), ',') AS SCHEDULE_DT_SRNOS
    FROM SCHEDULE_DETAIL SD
    INNER JOIN SCHEDULE_MASTER SM ON SD.SCHEDULE_SRNO = SM.SCHEDULE_SRNO
    INNER JOIN M_GRADE G ON SD.GRADE_SRNO = G.GRADE_SRNO
    INNER JOIN M_THICKNESS T ON SD.THICKNESS_SRNO = T.THICKNESS_SRNO
    LEFT JOIN M_OD O ON SD.OD_SRNO = O.OD_SRNO
    WHERE 
        SM.SCHEDULE_SRNO IN (SELECT SCHEDULE_SRNO FROM @TempScheduleSrnos)
        AND SD.DEL_FLAG = 0
        AND SM.DEL_FLAG = 0
        --AND SD.STATUS_SRO = 11 -- Pending status
    GROUP BY 
        G.GRADE,
        G.GRADE_SRNO,
        T.THICKNESS,
        T.THICKNESS_SRNO,
        O.OD,
        O.OD_SRNO,
        SM.ITEM_TYPE,
		SM.PARTY_NAME,
		SM.PO_NUMBER
    HAVING 
        COUNT(*) > 0;
	 END

