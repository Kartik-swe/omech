CREATE FUNCTION [dbo].[FN_CALCULATE_PIPE_WEIGHT_BY_VALUES]
(
    @OD DECIMAL(18,2),
    @THICKNESS DECIMAL(18,2),
    @LENGTH DECIMAL(18,2),
    @FACTOR DECIMAL(18,5),
    @QUANTITY INT
)
RETURNS DECIMAL(18,2)
AS
BEGIN
    DECLARE @WEIGHT DECIMAL(18,2);
    
    SET @WEIGHT = ((@OD - @THICKNESS) * @THICKNESS * @LENGTH * @FACTOR) * @QUANTITY;
    
    RETURN @WEIGHT;
END;
