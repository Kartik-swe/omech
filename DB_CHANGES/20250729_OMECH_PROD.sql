ALTER   PROCEDURE [dbo].[DT_SCHEDULE]
    @ITEM_TYPE NVARCHAR(20) = NULL,
    @PARTY_NAME NVARCHAR(100) = NULL,
    @STATUS_SRNO INT = NULL,
    @ENTRY_DATE_FROM DATE = NULL,
    @ENTRY_DATE_TO DATE = NULL,
    @DELIVERY_DATE_FROM DATE = NULL,
    @DELIVERY_DATE_TO DATE = NULL,
    @USER_SRNO NUMERIC(18,0)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        SM.SCHEDULE_SRNO,
        SM.PARTY_NAME,
        SM.ITEM_TYPE,
        SM.PO_NUMBER,
		dbo.FN_FMT_DATE(SM.SCHEDULE_DATE) AS SCHEDULE_DATE,
		dbo.FN_FMT_DATE(SM.ESTIMATED_DELIVERY_DATE) AS ESTIMATED_DELIVERY_DATE,
        SM.REMARKS,
        MS.STATUS_NAME,
		SM.STATUS_SRNO,
        SUM(SD.QUANTITY) AS T_ORDER_QTY,
        CASE 
            WHEN SM.ITEM_TYPE = 'PIPE' THEN SUM(SD.QUANTITY * SD.WEIGHT_PER_QTY)
            ELSE SUM(SD.WEIGHT_KG)
        END AS T_ORDER_WEIGHT,
		CASE 
			WHEN DATEDIFF(DAY, GETDATE(), SM.ESTIMATED_DELIVERY_DATE) BETWEEN 0 AND 7 THEN 'Y'
			ELSE 'N'
		END AS IS_URGENT_DELIVERY

    FROM SCHEDULE_MASTER SM
        INNER JOIN SCHEDULE_DETAIL SD ON SD.SCHEDULE_SRNO = SM.SCHEDULE_SRNO
        LEFT OUTER JOIN M_STATUS MS ON MS.STATUS_SRNO = SM.STATUS_SRNO
    WHERE 
        SM.DEL_FLAG = 0
        AND (@ITEM_TYPE IS NULL OR SM.ITEM_TYPE = @ITEM_TYPE)
        AND (@PARTY_NAME IS NULL OR SM.PARTY_NAME LIKE '%' + @PARTY_NAME + '%')
		AND (@STATUS_SRNO IS NULL OR SM.STATUS_SRNO = @STATUS_SRNO)
        AND (@ENTRY_DATE_FROM IS NULL OR SM.SCHEDULE_DATE >= @ENTRY_DATE_FROM)
        AND (@ENTRY_DATE_TO IS NULL OR SM.SCHEDULE_DATE <= @ENTRY_DATE_TO)
        AND (@DELIVERY_DATE_FROM IS NULL OR SM.ESTIMATED_DELIVERY_DATE >= @DELIVERY_DATE_FROM)
        AND (@DELIVERY_DATE_TO IS NULL OR SM.ESTIMATED_DELIVERY_DATE <= @DELIVERY_DATE_TO)
    GROUP BY
        SM.SCHEDULE_SRNO,
        SM.PARTY_NAME,
        SM.ITEM_TYPE,
        SM.PO_NUMBER,
        SM.SCHEDULE_DATE,
        SM.ESTIMATED_DELIVERY_DATE,
        SM.REMARKS,
        MS.STATUS_NAME,
		SM.STATUS_SRNO
    ORDER BY SM.SCHEDULE_SRNO DESC
END
