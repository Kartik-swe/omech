    INNER JOIN M_VENDORS MV ON RM.C_LOCATION = MV.VENDOR_SRNO
    INNER JOIN M_GRADE G ON RM.MATERIAL_GRADE_SRNO = G.GRADE_SRNO
    INNER JOIN M_THICKNESS T ON RM.MATERIAL_THICKNESS_SRNO = T.THICKNESS_SRNO
    INNER JOIN M_STATUS S ON RM.MATERIAL_STATUS_SRNO = S.STATUS_SRNO
	INNER JOIN M_USER U ON RM.CREATED_BY = U.USER_SRNO
    wHERE RM.MATERIAL_SRNO IN (SELECT MATERIAL_SRNO FROM @RawMaterialTable)

    ORDER BY RM.CREATED_AT DESC; -- Order by creation date (latest first)

