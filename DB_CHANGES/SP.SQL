CREATE   PROCEDURE [dbo].[DEL_SLITTING_PROCESSES]
	@SLITTING_SRNO NUMERIC,
    @USER_SRNO INT NULL
	
AS
BEGIN
	
	 -- Start by declaring a table variable to hold all descendant records
    DECLARE @DeleteList TABLE (SLITTING_SRNO INT);

    -- Ensure that the previous statement ends with a semicolon (important for CTE)
    ;WITH Hierarchy AS (
        -- Select the record to be deleted
        SELECT SLITTING_SRNO
        FROM SLITTING_PROCESSES
        WHERE SLITTING_SRNO = @SLITTING_SRNO
        
        UNION ALL
        
        -- Recursively select child records
        SELECT t.SLITTING_SRNO
        FROM SLITTING_PROCESSES t
        INNER JOIN Hierarchy h ON t.SLITTING_SRNO_FK = h.SLITTING_SRNO
    )
    -- Insert the results into the table variable
    INSERT INTO @DeleteList (SLITTING_SRNO)
    SELECT SLITTING_SRNO FROM Hierarchy;

    -- Delete all the records identified in the CTE
    UPDATE SLITTING_PROCESSES
		SET 
			DEL_FLAG = 1,
			DEL_BY = @USER_SRNO,
			DEL_AT = GETDATE()
    WHERE SLITTING_SRNO IN (SELECT SLITTING_SRNO FROM @DeleteList);

	-- Delete all the records identified in the CTE
    UPDATE MATERIAL_SHIFTING_HISTORY
		SET 
			DEL_FLAG = 1,
			DEL_BY = @USER_SRNO,
			DEL_AT = GETDATE()
    WHERE SLITTING_SRNO IN (SELECT SLITTING_SRNO FROM @DeleteList);

