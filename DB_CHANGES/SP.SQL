CREATE    PROCEDURE [dbo].[DISP_DISPATCH_SCHEDULE]
    @SCHEDULE_SRNO INT,
    @USER_SRNO INT -- included for audit/logging if needed
AS
BEGIN
    SET NOCOUNT ON;

	 -- 1. Fetch master data
    SELECT 
        SM.SCHEDULE_SRNO,
        SM.PARTY_NAME,
        SM.PO_NUMBER,
        SM.SCHEDULE_DATE,
        SM.ESTIMATED_DELIVERY_DATE,
        SM.STATUS_SRNO,
        SM.REMARKS
		

    FROM SCHEDULE_MASTER SM
    WHERE SM.SCHEDULE_SRNO = @SCHEDULE_SRNO;



    -- 2. Fetch related detail rows
    SELECT 
        SD.SCHEDULE_DT_SRNO,
        SD.SCHEDULE_SRNO,
        MG.GRADE,
		MO.OD,
		MT.THICKNESS,
        SD.LENGTH,
		SD.WIDTH,
		SD.BREADTH,
		CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN SD.WEIGHT_PER_QTY  * SD.QUANTITY  ELSE SD.WEIGHT_KG END AS ORDERED_WEIGHT,
		CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN SD.WEIGHT_PER_QTY  * (SD.QUANTITY - (ISNULL(SD.DISPATCHED_QTY, 0) - ISNULL(RJ.TOTAL_REJECTED_QTY, 0) )) ELSE SD.WEIGHT_KG - ISNULL(DISPATCHED_WEIGHT_KG,0) END AS REMAINING_WEIGHT,
		CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN SD.WEIGHT_PER_QTY  * ISNULL(SD.DISPATCHED_QTY, 0) ELSE isnull(SD.DISPATCHED_WEIGHT_KG,0) END AS DISPATCHED_WEIGHT,
		--SD.WEIGHT_KG,
        --SD.WEIGHT_PER_QTY  *SD.QUANTITY  AS ORDERED_WEIGHT,
        --SD.WEIGHT_PER_QTY  * ISNULL(SD.DISPATCHED_QTY, 0)  AS DISPATCHED_WEIGHT,
        -- SD.WEIGHT_PER_QTY  *(SD.QUANTITY - (ISNULL(SD.DISPATCHED_QTY, 0) - ISNULL(RJ.TOTAL_REJECTED_QTY, 0) )  )  AS REMAINING_WEIGHT,
        SD.WEIGHT_PER_QTY  *ISNULL(RJ.TOTAL_REJECTED_QTY, 0)  AS REJECTED_WEIGHT,

        SD.QUANTITY  AS ORDERED_QTY,
        SD.STATUS_SRNO,
		ISNULL(SD.DISPATCHED_QTY, 0) AS DISPATCHED_QTY,
        (SD.QUANTITY - (ISNULL(SD.DISPATCHED_QTY, 0) - ISNULL(RJ.TOTAL_REJECTED_QTY, 0) )  ) AS REMAINING_QTY,
		CASE WHEN SD.STATUS_SRNO = 13 THEN 'Y' ELSE 'N' END AS IS_CLOSED,
		ISNULL(RJ.TOTAL_REJECTED_QTY, 0) AS REJECTED_QTY,
		CASE WHEN SD.STATUS_SRNO = 11 THEN 'P' WHEN SD.STATUS_SRNO = 12 THEN 'C' WHEN SD.STATUS_SRNO = 13 THEN 'E' ELSE 'P' END AS STATUS_FLAG,
		CASE WHEN SD.STATUS_SRNO = 11 THEN 'Pending' WHEN SD.STATUS_SRNO = 12 THEN 'Completed' WHEN SD.STATUS_SRNO = 13 THEN 'Closed' ELSE 'Pending' END AS STATUS_NAME
    FROM SCHEDULE_DETAIL SD
	LEFT JOIN SCHEDULE_MASTER SM ON SM.SCHEDULE_SRNO = SD.SCHEDULE_SRNO
	LEFT JOIN (
			SELECT 
				SCHEDULE_DT_SRNO,
				SUM(REJECTED_QTY) AS TOTAL_REJECTED_QTY
			FROM PO_ITEMS_REJECT
			GROUP BY SCHEDULE_DT_SRNO
		) RJ ON RJ.SCHEDULE_DT_SRNO = SD.SCHEDULE_DT_SRNO
 	LEFT JOIN M_GRADE MG ON MG.GRADE_SRNO = SD.GRADE_SRNO
	LEFT JOIN M_OD MO ON MO.OD_SRNO = SD.OD_SRNO
	LEFT JOIN M_THICKNESS MT ON MT.THICKNESS_SRNO = SD.THICKNESS_SRNO
    WHERE SD.SCHEDULE_SRNO = @SCHEDULE_SRNO;


	SELECT 
		SM.SCHEDULE_SRNO,
		SD.SCHEDULE_DT_SRNO,
		SDISP.DISPATCH_SRNO,
		SDISP.DISPATCH_DATE,
		CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN SDISP.DISPATCH_QTY ELSE SDISP.DISPATCHED_WEIGHT_KG END AS DISPATCH_QTY

	FROM  SCHEDULE_MASTER SM
	INNER JOIN SCHEDULE_DETAIL SD ON SD.SCHEDULE_SRNO = SM.SCHEDULE_SRNO
	INNER JOIN SCHEDULE_DISPATCH SDISP ON SDISP.SCHEDULE_DT_SRNO = SD.SCHEDULE_DT_SRNO
	WHERE SM.SCHEDULE_SRNO = @SCHEDULE_SRNO




