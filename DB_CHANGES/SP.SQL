    UPDATE T_LOG_MATERIAL_STATUS
		SET 
			DEL_FLAG = 1,
			DEL_BY = @USER_SRNO,
			DEL_AT = GETDATE()
    WHERE SLITTING_SRNO IN (SELECT SLITTING_SRNO FROM @DeleteList);

