    INSERT INTO @RawMaterialTable (MATERIAL_SRNO)
    SELECT RM.MATERIAL_SRNO
    FROM RAW_MATERIALS RM
    WHERE 
        RM.DEL_FLAG = 0 -- Only include active records
         AND (
                (@IS_SHOW_ALL = 'Y' AND RM.MATERIAL_STATUS_SRNO IN (4,5,8,9)) OR
                (@IS_SHOW_ALL <> 'Y' AND RM.MATERIAL_STATUS_SRNO IN (4,5,8))
