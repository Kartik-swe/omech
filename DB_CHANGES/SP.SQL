    @TRN_BY NUMERIC(18,0),
    @TRN_REMARK NVARCHAR(100),
    @USER_SRNO NUMERIC(18,0)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        -- Start a transaction
        BEGIN TRANSACTION

        DECLARE @PIPE_TRN_TYPE_SRNO NUMERIC(18,0) = 2;
		SET @TRN_DATE = GETDATE();
	SET @TRN_BY = @USER_SRNO;
        -- Reduce quantity from the source location
        UPDATE PIPE_INVENTORY
        SET AVAILABLE_QUANTITY = AVAILABLE_QUANTITY - @PIPE_NOS
        WHERE PR_INV_SRNO = @PR_INV_SRNO
          AND PR_SRNO = @PR_SRNO
          AND C_LOCATION = @FROM_LOCATION
          AND AVAILABLE_QUANTITY >= @PIPE_NOS;

        -- Check if there was enough quantity to reduce, else raise an error
        IF @@ROWCOUNT = 0
        BEGIN
            THROW 50001, 'Insufficient quantity in source location.', 1;
        END

        -- Add quantity to the new location
        IF EXISTS (SELECT 1 FROM PIPE_INVENTORY WHERE PR_SRNO = @PR_SRNO AND C_LOCATION = @TO_LOCATION)
        BEGIN
            UPDATE PIPE_INVENTORY
            SET AVAILABLE_QUANTITY = AVAILABLE_QUANTITY + @PIPE_NOS
            WHERE PR_SRNO = @PR_SRNO 
              AND C_LOCATION = @TO_LOCATION;
        END
