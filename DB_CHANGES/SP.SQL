            PG_DONE_BY = @USER_SRNO,
            PG_DONE_AT = @PG_DONE_AT,
            MODIFIED_BY = @USER_SRNO,
            MODIFIED_AT = GETDATE()
        WHERE PG_SRNO = @PG_SRNO;

        -- Soft delete old pipes
        UPDATE PIPE_DT 
        SET DEL_FLAG = 1, DEL_BY = @USER_SRNO, DEL_AT = GETDATE()
        WHERE PG_SRNO = @PG_SRNO;
    END

    -- Insert Pipes into PIPE_DT
    WHILE @COUNTER <= @PIPE_NOS
    BEGIN
        INSERT INTO PIPE_DT (
            PG_SRNO, PIPE_NAME, P_LENGTH, P_WEIGHT, C_LOCATION, 
            DEL_FLAG, CREATED_BY, CREATED_AT
        )
        VALUES (
            @PG_SRNO, @PIPE_NAME, @P_LENGTH, @P_WEIGHT, @C_LOCATION, 
            0, @USER_SRNO, GETDATE()
        );
        SET @COUNTER = @COUNTER + 1;
    END;

    -- Handle Coil Completion
    IF @IS_COIL_COMPLETED = 1
    BEGIN
        IF @SLITTING_SRNO > 0
            UPDATE SLITTING_PROCESSES
            SET STATUS_SRNO = 10 -- Shifted to production
            WHERE SLITTING_SRNO = @SLITTING_SRNO;
        ELSE
            UPDATE RAW_MATERIALS
            SET MATERIAL_STATUS_SRNO = 10 -- Shifted to production
            WHERE MATERIAL_SRNO = @MATERIAL_SRNO;
        
        -- Log status change
        EXEC IU_STATUS_LOG @MATERIAL_SRNO, @SLITTING_SRNO, @PRE_LOG_STATUS_SRNO, NULL, NULL, @PG_DONE_AT, @USER_SRNO, @UT_SRNO, 0;
    END;

    SELECT @PG_SRNO AS PG_SRNO;
END;
