        SELECT 
            RM.MATERIAL_SRNO,
            RM.CHALLAN_NO,
            RM.MATERIAL_WIDTH,
			RM.MATERIAL_WIDTH - ISNULL(FN.SLITTED_WIDTH, 0) AS BALANCE_WIDTH,
