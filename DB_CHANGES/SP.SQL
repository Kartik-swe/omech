CREATE   PROCEDURE [dbo].[SP_IU_SLITTING_PROCESSES]
    @MATERIAL_SRNO INT,
    @C_LOCATION INT,
	@SLITTING_SRNO_FK INT,
	@SLITTING_LEVEL INT,
    @SLITTING_DATE DATETIME,
    @DC_NO VARCHAR(100),
   -- @SHIFT_TO INT,
    @SCRAP VARCHAR(100),
	@SLITTING_SCRAP_WEIGHT DECIMAL(10, 2),
    @CREATED_BY INT,
    @slitDetails NVARCHAR(MAX) -- JSON containing width, nos, and weights
AS
BEGIN
    SET NOCOUNT ON;	

    -- Begin Transaction
    BEGIN TRANSACTION;

    BEGIN TRY
        -- Declare variables
        DECLARE @width VARCHAR(10), @nos INT, @weight DECIMAL(10, 2);
        DECLARE @json NVARCHAR(MAX) = @slitDetails;
        DECLARE @i INT; -- Counter variable

        -- Parse and insert dynamic slit details based on Level
        IF (ISJSON(@slitDetails) = 1)
        BEGIN
            -- Declare cursor outside the JSON parsing logic to ensure it's not redeclared
            DECLARE slit_cursor CURSOR FOR
            SELECT 
                JSON_VALUE(value, '$.SLITTING_WIDTH') AS width,
                JSON_VALUE(value, '$.NOS') AS nos,
                ROUND(JSON_VALUE(value, '$.SLITTING_WEIGHT'),2) AS weight
            FROM OPENJSON(@json);

            OPEN slit_cursor;

            FETCH NEXT FROM slit_cursor INTO @width, @nos, @weight;

            -- Loop to insert the required number of rows based on 'nos'
            WHILE @@FETCH_STATUS = 0
            BEGIN
                -- Initialize counter variable for each width/nos combination
                SET @i = 1;

                -- Check if the level is 1
                
                    -- Insert rows for Level 1 with SLITTING_SRNO_FK as NULL
                    WHILE @i <= @nos
                    BEGIN
                        INSERT INTO [dbo].[SLITTING_PROCESSES] (
                            MATERIAL_SRNO,
                            SLITTING_SRNO_FK,  -- NULL for Level 1
							SLITTING_LEVEL,
                            C_LOCATION,
                            SLITTING_DATE,
                            SLITTING_WIDTH,
                            SLITTING_WEIGHT,
							DC_NO,
							--SHIFT_TO,
							--SLITTING_SCRAP,
							STATUS_SRNO,
                            CREATED_AT,
                            CREATED_BY,
                            DEL_FLAG
                        )
                        VALUES (
                            @MATERIAL_SRNO,
                            @SLITTING_SRNO_FK,  -- For Level 1, SLITTING_SRNO_FK is NULL
							@SLITTING_LEVEL,
                            @C_LOCATION,
                            @SLITTING_DATE,
                            @width,
                            @weight,
							@DC_NO,
							--@SHIFT_TO,
							--@SCRAP,
							4, --NEW
                            GETDATE(),
                            @CREATED_BY,
                            0
                        );
                        SET @i = @i + 1;  -- Increment counter
                END
               

                FETCH NEXT FROM slit_cursor INTO @width, @nos, @weight;
            END;

            CLOSE slit_cursor;
            DEALLOCATE slit_cursor;  -- Deallocate cursor to free resources

			
			UPDATE [dbo].[RAW_MATERIALS]
				SET 
					MATERIAL_SCRAP = ISNULL(MATERIAL_SCRAP, 0) + CASE WHEN @SLITTING_LEVEL = 1 THEN @SCRAP ELSE 0 END,
					SLIT_MATERIAL_SCRAP = ISNULL(SLIT_MATERIAL_SCRAP, 0) + CASE WHEN @SLITTING_LEVEL > 1 THEN @SCRAP ELSE 0 END,

					MATERIAL_SCRAP_WEIGHT = ISNULL(MATERIAL_SCRAP_WEIGHT, 0) + CASE WHEN @SLITTING_LEVEL = 1 THEN @SLITTING_SCRAP_WEIGHT ELSE 0 END,
					SLIT_MATERIAL_SCRAP_WEIGHT = ISNULL(SLIT_MATERIAL_SCRAP_WEIGHT, 0) + CASE WHEN @SLITTING_LEVEL > 1 THEN @SLITTING_SCRAP_WEIGHT ELSE 0 END
				WHERE MATERIAL_SRNO = @MATERIAL_SRNO;



			-- Update Scrap in SLITTING_PROCESSES for SLITTING_SRNO_FK
			UPDATE [dbo].[SLITTING_PROCESSES]
			SET 
				SLITTING_SCRAP = ISNULL(SLITTING_SCRAP, 0) + ISNULL(@SCRAP,0),
				SLITTING_SCRAP_WEIGHT = ISNULL(SLITTING_SCRAP_WEIGHT, 0) + ISNULL(@SLITTING_SCRAP_WEIGHT,0)
			WHERE SLITTING_SRNO = @SLITTING_SRNO_FK;

			 -- **Update Parent Slitting Status (if it has a parent)**
            IF @SLITTING_SRNO_FK IS NOT NULL
                EXEC SP_UPDATE_SLITTING_STATUS @SLITTING_SRNO_FK;

			-- **CALL STATUS UPDATE PROCEDURE**
			If @SLITTING_LEVEL =1 
			BEGIN
				EXEC SP_UPDATE_RAW_MATERIAL_STATUS @MATERIAL_SRNO;
			END

        END

        -- Commit the transaction
        COMMIT TRANSACTION;
		SELECT SCOPE_IDENTITY() AS SLITTING_SRNO;

    END TRY
    BEGIN CATCH
        -- Rollback transaction in case of error
        ROLLBACK TRANSACTION;

        -- Throw the error
        THROW;
    END CATCH
END
