--DT_THRESHOLD_DISPLAY 
CREATE   PROCEDURE [dbo].[DT_THRESHOLD_DISPLAY]
@GRADE_SRNO INT = NULL,
    @THICKNESS_SRNO INT = NULL,
    @OD_SRNO INT = NULL,
    @USER_SRNO INT = NULL
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TOLERANCE INT = 5;

    SELECT 
        TH.THRESHOLD_SRNO,
		MG.GRADE,
		MT.THICKNESS,
		MO.OD,
        TH.MIN_THRESHOLD,
        TH.REQUIRED_WIDTH,
        ISNULL(SUM(SP.SLITTING_WEIGHT), 0) AS TOTAL_SLITTING_WEIGHT,
		CASE 
			WHEN ISNULL(SUM(SP.SLITTING_WEIGHT), 0) < TH.MIN_THRESHOLD THEN 'below'
			WHEN ISNULL(SUM(SP.SLITTING_WEIGHT), 0) BETWEEN TH.MIN_THRESHOLD 
													   AND (TH.MIN_THRESHOLD + @TOLERANCE) THEN 'near'
			ELSE 'above'
		END AS STATUS
    FROM M_THRESHOLD TH
    INNER JOIN M_GRADE MG ON MG.GRADE_SRNO = TH.GRADE_SRNO
	INNER JOIN M_THICKNESS MT ON MT.THICKNESS_SRNO = TH.THICKNESS_SRNO
	INNER JOIN M_OD MO ON MO.OD_SRNO = TH.OD_SRNO
	LEFT JOIN RAW_MATERIALS RM ON RM.MATERIAL_GRADE_SRNO = TH.GRADE_SRNO AND RM.MATERIAL_THICKNESS_SRNO = TH.THICKNESS_SRNO AND RM.DEL_FLAG = 0
	LEFT JOIN SLITTING_PROCESSES SP ON SP.MATERIAL_SRNO = RM.MATERIAL_SRNO
		AND SP.DEL_FLAG = 0 AND SP.IS_SLITTED =1 AND SP.STATUS_SRNO = 8
		AND SP.SLITTING_WIDTH BETWEEN TH.REQUIRED_WIDTH - @TOLERANCE AND TH.REQUIRED_WIDTH + @TOLERANCE
    GROUP BY 
        TH.THRESHOLD_SRNO,
		MG.GRADE,
		MT.THICKNESS,
		MO.OD,
        TH.MIN_THRESHOLD,
        TH.REQUIRED_WIDTH
    ORDER BY TH.THRESHOLD_SRNO;


	-- =========================
    -- Second result set: Summary Statistics
    -- =========================
    SELECT 
        COUNT(1) AS TOTAL_RECORDS,
        SUM(CASE WHEN X.STATUS = 'BELOW_THRESHOLD' THEN 1 ELSE 0 END) AS BELOW_THRESHOLD,
        SUM(CASE WHEN X.STATUS = 'NEAR_THRESHOLD' THEN 1 ELSE 0 END) AS NEAR_THRESHOLD,
        SUM(CASE WHEN X.STATUS = 'ABOVE_THRESHOLD' THEN 1 ELSE 0 END) AS ABOVE_THRESHOLD,
        SUM(X.TOTAL_SLITTING_WEIGHT) AS TOTAL_AVAILABLE_WEIGHT
    FROM (
        SELECT 
            TH.THRESHOLD_SRNO,
            ISNULL(SUM(SP.SLITTING_WEIGHT), 0) AS TOTAL_SLITTING_WEIGHT,
            CASE 
                WHEN ISNULL(SUM(SP.SLITTING_WEIGHT), 0) < TH.MIN_THRESHOLD THEN 'BELOW_THRESHOLD'
                WHEN ISNULL(SUM(SP.SLITTING_WEIGHT), 0) BETWEEN TH.MIN_THRESHOLD 
                                                           AND (TH.MIN_THRESHOLD + @TOLERANCE) THEN 'NEAR_THRESHOLD'
                ELSE 'ABOVE_THRESHOLD'
            END AS STATUS
        FROM M_THRESHOLD TH
        LEFT JOIN RAW_MATERIALS RM 
            ON RM.MATERIAL_GRADE_SRNO = TH.GRADE_SRNO
           AND RM.MATERIAL_THICKNESS_SRNO = TH.THICKNESS_SRNO
           AND RM.DEL_FLAG = 0
        LEFT JOIN SLITTING_PROCESSES SP
            ON SP.MATERIAL_SRNO = RM.MATERIAL_SRNO
            AND SP.DEL_FLAG = 0
            AND SP.IS_SLITTED = 1
            AND SP.STATUS_SRNO = 8
            AND SP.SLITTING_WIDTH BETWEEN TH.REQUIRED_WIDTH - @TOLERANCE 
                                      AND TH.REQUIRED_WIDTH + @TOLERANCE
        WHERE 
            (@GRADE_SRNO IS NULL OR TH.GRADE_SRNO = @GRADE_SRNO)
            AND (@THICKNESS_SRNO IS NULL OR TH.THICKNESS_SRNO = @THICKNESS_SRNO)
            AND (@OD_SRNO IS NULL OR TH.OD_SRNO = @OD_SRNO)
        GROUP BY 
            TH.THRESHOLD_SRNO,
            TH.MIN_THRESHOLD,
            TH.REQUIRED_WIDTH
    ) X;
END
