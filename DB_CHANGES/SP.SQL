                @FROM_LOCATION, @PIPE_TRN_TYPE_SRNO, @TRN_DATE, @TRN_BY, @TRN_REMARK,
                0, NULL, NULL, @USER_SRNO, GETDATE());

        -- Commit transaction
        COMMIT TRANSACTION;
		SELECT @PR_INV_SRNO AS PR_INV_SRNO;

    END TRY
    BEGIN CATCH
        -- Rollback transaction in case of error
        ROLLBACK TRANSACTION;

        -- Throw the error message
        THROW;
