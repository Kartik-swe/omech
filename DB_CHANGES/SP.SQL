CREATE   PROCEDURE [dbo].[IU_SCHEDULE]
    @IU_FLAG CHAR(1), -- 'I' or 'U'
    @PARTY_NAME NVARCHAR(255),
    @PO_NUMBER NVARCHAR(100),
    @SCHEDULE_DATE DATE,
    @ESTIMATED_DELIVERY_DATE DATE = NULL,
    @STATUS_SRNO INT,
    @REMARKS NVARCHAR(MAX) = NULL,
    @ITEM_TYPE VARCHAR(10),  -- NEW PARAMETER
    @DETAIL_JSON NVARCHAR(MAX), -- JSON array of details

    @UT_SRNO INT = NULL,
    @USER_SRNO INT,
    @SCHEDULE_SRNO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    IF @IU_FLAG = 'I'
    BEGIN
        SET @STATUS_SRNO = 11
        INSERT INTO SCHEDULE_MASTER (
            PARTY_NAME, PO_NUMBER, SCHEDULE_DATE, ESTIMATED_DELIVERY_DATE,
            STATUS_SRNO, REMARKS, ITEM_TYPE, CREATED_AT, CREATED_BY
        )
        VALUES (
            @PARTY_NAME, @PO_NUMBER, @SCHEDULE_DATE, @ESTIMATED_DELIVERY_DATE,
            @STATUS_SRNO, @REMARKS, @ITEM_TYPE, GETDATE(), @USER_SRNO
        );

        SET @SCHEDULE_SRNO = SCOPE_IDENTITY();
    END
    ELSE IF @IU_FLAG = 'U'
    BEGIN
        UPDATE SCHEDULE_MASTER
        SET
            PARTY_NAME = @PARTY_NAME,
            PO_NUMBER = @PO_NUMBER,
            SCHEDULE_DATE = @SCHEDULE_DATE,
            ESTIMATED_DELIVERY_DATE = @ESTIMATED_DELIVERY_DATE,
            --STATUS_SRNO = @STATUS_SRNO,
            REMARKS = @REMARKS,
           -- ITEM_TYPE = @ITEM_TYPE,
            MODIFIED_AT = GETDATE(),
            MODIFIED_BY = @USER_SRNO
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO;
    END

    -- Parse Detail JSON
    ;WITH DetailDataRaw AS (
        SELECT *
        FROM OPENJSON(@DETAIL_JSON)
        WITH (
            SCHEDULE_DT_SRNO INT,
            --ITEM_TYPE VARCHAR(10),
            OD_SRNO INT,
            THICKNESS_SRNO INT,
            GRADE_SRNO INT,
            LENGTH DECIMAL(10,2),
            QUANTITY INT,
            WIDTH DECIMAL(10,2),
            BREADTH DECIMAL(10,2),
            WEIGHT_KG DECIMAL(10,2),
            STATUS_SRNO INT
        )
    ),
    DetailData AS (
        SELECT 
            D.*,
            OD.OD,
            T.THICKNESS,
           CASE 
			  WHEN OD.OD IS NOT NULL AND T.THICKNESS IS NOT NULL AND D.LENGTH IS NOT NULL THEN
				CAST(
				  (CAST(OD.OD AS FLOAT) - CAST(T.THICKNESS AS FLOAT)) 
				  * CAST(T.THICKNESS AS FLOAT) 
				  * CAST(D.LENGTH AS FLOAT) 
				  * 0.00002485 
				  AS DECIMAL(18,4)
				)
			  ELSE NULL
			END AS WEIGHT_PER_QTY
