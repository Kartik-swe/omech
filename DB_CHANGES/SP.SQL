            TM.THICKNESS AS MATERIAL_THICKNESS,  -- Thickness from Thickness Master
            GM.GRADE AS MATERIAL_GRADE,         -- Grade from Grade Master
            VM.VENDOR_NAME AS FROM_LOCATION,    -- Vendor name for C_LOCATION
            CASE 
                WHEN EXISTS (
                    SELECT 1
                    FROM SLITTING_PROCESSES SP
                    WHERE SP.MATERIAL_SRNO = RM.MATERIAL_SRNO
                      AND SP.DEL_FLAG = 0
                ) THEN 'Y'
                ELSE 'N'
            END AS IS_RAW_SLITTED,  -- Flag to indicate if material is 
			RM.MATERIAL_STATUS_SRNO AS LOG_STATUS_SRNO
        FROM 
            RAW_MATERIALS RM
        LEFT JOIN M_THICKNESS TM 
            ON RM.MATERIAL_THICKNESS_SRNO = TM.THICKNESS_SRNO
        LEFT JOIN M_GRADE GM 
            ON RM.MATERIAL_GRADE_SRNO = GM.GRADE_SRNO
