            SET @PR_SRNO = SCOPE_IDENTITY();
        END
        ELSE
        BEGIN
            SELECT @PR_SRNO = PR_SRNO FROM PR_MASTER WHERE PR_NAME = @PIPE_NAME AND PR_LENGTH = @P_LENGTH AND PR_WEIGHT = @P_WEIGHT;
        END

        -- Insert into PIPE_INVENTORY if not exists
        IF NOT EXISTS (SELECT 1 FROM PIPE_INVENTORY WHERE PR_SRNO = @PR_SRNO AND C_LOCATION = @C_LOCATION)
        BEGIN
            INSERT INTO PIPE_INVENTORY (PR_SRNO, C_LOCATION, AVAILABLE_QUANTITY,CREATED_BY, CREATED_AT)
            VALUES (@PR_SRNO, @C_LOCATION, @PIPE_NOS, @USER_SRNO, GETDATE());
            SET @PR_INV_SRNO = SCOPE_IDENTITY();
        END
        ELSE
        BEGIN
            SELECT @PR_INV_SRNO = PR_INV_SRNO FROM PIPE_INVENTORY WHERE PR_SRNO = @PR_SRNO AND C_LOCATION = @C_LOCATION;
            UPDATE PIPE_INVENTORY SET AVAILABLE_QUANTITY = AVAILABLE_QUANTITY + @PIPE_NOS WHERE PR_INV_SRNO = @PR_INV_SRNO;
        END

        -- Insert into PIPE_INVENTORY_LOG
        INSERT INTO PIPE_INVENTORY_LOG (PR_SRNO, C_LOCATION, QUANTITY, MACHINE_SRNO, MATERIAL_SRNO, SLITTING_SRNO,
										FROM_LOCATION,PIPE_TRN_TYPE_SRNO,TRN_DATE,TRN_BY,TRN_REMARK,
