    @DETAIL_JSON NVARCHAR(MAX), -- JSON array of details

    @UT_SRNO INT = NULL,
    @USER_SRNO INT,
    @SCHEDULE_SRNO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    IF @IU_FLAG = 'I'
    BEGIN
        SET @STATUS_SRNO = 11
        INSERT INTO SCHEDULE_MASTER (
            PARTY_NAME, PO_NUMBER, SCHEDULE_DATE, ESTIMATED_DELIVERY_DATE,
            STATUS_SRNO, REMARKS, ITEM_TYPE, CREATED_AT, CREATED_BY
