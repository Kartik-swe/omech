CREATE     PROCEDURE [dbo].[SP_UPDATE_SLITTING_STATUS]
    @SLITTING_SRNO INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @TOTAL_CHILD_WIDTH DECIMAL(10,2);
    DECLARE @SLITTING_WIDTH DECIMAL(10,2);
    DECLARE @SLITTING_SCRAP DECIMAL(10,2);
    DECLARE @CHILD_COUNT INT;

    -- Get Slitting Width and Scrap
    SELECT 
        @SLITTING_WIDTH = CAST(SLITTING_WIDTH AS DECIMAL(10,2)), 
        @SLITTING_SCRAP = ISNULL(SLITTING_SCRAP, 0)
    FROM SLITTING_PROCESSES
    WHERE SLITTING_SRNO = @SLITTING_SRNO;

    -- Sum all child SLITTING_WIDTH values
    SELECT 
        @TOTAL_CHILD_WIDTH = ISNULL(SUM(CAST(SLITTING_WIDTH AS DECIMAL(10,2))), 0),
        @CHILD_COUNT = COUNT(*)
    FROM SLITTING_PROCESSES
    WHERE SLITTING_SRNO_FK = @SLITTING_SRNO AND DEL_FLAG = 0;

    -- Determine Status
    IF @CHILD_COUNT = 0
        UPDATE SLITTING_PROCESSES 
        SET STATUS_SRNO = 4 -- NEW
        WHERE SLITTING_SRNO = @SLITTING_SRNO;
    ELSE IF (@TOTAL_CHILD_WIDTH + @SLITTING_SCRAP) >= @SLITTING_WIDTH
        UPDATE SLITTING_PROCESSES 
        SET STATUS_SRNO = 9 -- COMPLETE
        WHERE SLITTING_SRNO = @SLITTING_SRNO;
    ELSE
        UPDATE SLITTING_PROCESSES 
        SET STATUS_SRNO = 5 --'In Slitting'
        WHERE SLITTING_SRNO = @SLITTING_SRNO;
END;
GO
