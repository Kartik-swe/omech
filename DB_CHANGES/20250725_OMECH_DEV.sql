            WHERE 
                SP.DEL_FLAG = 0
                AND RM.DEL_FLAG = 0
                AND SP.STATUS_SRNO IN (4,5,8)
                AND (@F_DATE IS NULL OR SP.CREATED_AT >= @F_DATE) 
                AND (@TO_DATE IS NULL OR SP.CREATED_AT <= @TO_DATE)
                AND (@STATUS_SRNO IS NULL OR SP.STATUS_SRNO = @STATUS_SRNO)
                AND (@WIDTH IS NULL OR SP.SLITTING_WIDTH - ISNULL(FN.SLITTED_WIDTH, 0) - ISNULL(SP.SLITTING_SCRAP, 0) = @WIDTH)
                AND (@GRADE_SRNO IS NULL OR RM.MATERIAL_GRADE_SRNO = @GRADE_SRNO)
                AND (@THICNESS_SRNO IS NULL OR RM.MATERIAL_THICKNESS_SRNO = @THICNESS_SRNO)
                AND (@C_LOCATION IS NULL OR SP.C_LOCATION = @C_LOCATION)
                AND ((@MATERIAL_FLAG = 'S' AND SP.IS_SLITTED = 1) OR (@MATERIAL_FLAG = 'P' AND SP.IS_SLITTED = 0) OR @MATERIAL_FLAG = 'A' OR @MATERIAL_FLAG = 'D');
        END;


		IF @MATERIAL_FLAG = 'D' 
		BEGIN
			SELECT 
				--SUM(CASE WHEN COIL_TYPE_FLAG = 'M'  AND STATUS_NAME='NEW' THEN BALANCE_WEIGHT ELSE 0 END) AS T_MOTHER_WEIGHT,
				--SUM(CASE WHEN (COIL_TYPE_FLAG = 'P') OR ( COIL_TYPE_FLAG = 'M' AND STATUS_NAME='In Slitting') THEN BALANCE_WEIGHT ELSE 0 END) AS T_SLITTING_WEIGHT,
				SUM(CASE WHEN COIL_TYPE_FLAG = 'M' THEN BALANCE_WEIGHT ELSE 0 END) AS T_MOTHER_WEIGHT,
				SUM(CASE WHEN COIL_TYPE_FLAG = 'P' THEN BALANCE_WEIGHT ELSE 0 END) AS T_SLITTING_WEIGHT,
				SUM(CASE WHEN COIL_TYPE_FLAG = 'S' THEN BALANCE_WEIGHT ELSE 0 END) AS T_SLITTED_WEIGHT,
				(SELECT ROUND(SUM(ISNULL(MATERIAL_SCRAP_WEIGHT, 0) + ISNULL(SLIT_MATERIAL_SCRAP_WEIGHT, 0)),2) FROM RAW_MATERIALS WHERE DEL_FLAG = 0) AS T_SCRAP,
				SUM(BALANCE_WEIGHT) AS T_STOCK
			FROM @TempResult;

			SELECT 
				GRADE,
				SUM(BALANCE_WEIGHT) AS T_WEIGHT
			FROM @TempResult 
			GROUP BY GRADE;

			SELECT 
				C_LOCATION,GRADE,
				SUM(BALANCE_WEIGHT) AS T_WEIGHT
			FROM @TempResult 
			GROUP BY GRADE,C_LOCATION;
		END

        ELSE 
		BEGIN
			-- Return Detailed Data
			SELECT 
				--CHALLAN_NO,
				C_LOCATION,
				BALANCE_WEIGHT,
				BALANCE_WIDTH,
				GRADE,
				THICKNESS,
				STATUS_NAME,
				COIL_TYPE_FLAG,
				STRING_AGG(SLITTING_SRNO, ',') AS SLITTING_SRNOS, 
				STRING_AGG(MATERIAL_SRNO, ',') AS MATERIAL_SRNOS, 
				COUNT(DISTINCT CASE WHEN COIL_TYPE_FLAG IN ('S', 'P') THEN SLITTING_SRNO ELSE MATERIAL_SRNO END) AS QUANTITY,
				CASE 
					WHEN COIL_TYPE_FLAG = 'S' THEN 'Slitted Coil' 
					WHEN COIL_TYPE_FLAG = 'P' THEN 'Semi Slitted Coil' 
					ELSE 'Mother Coil'
				END AS COIL_TYPE
			FROM @TempResult
			GROUP BY C_LOCATION, BALANCE_WEIGHT, BALANCE_WIDTH, GRADE, THICKNESS, STATUS_NAME, COIL_TYPE_FLAG;
        END

		select * from @TempResult
    END TRY
    BEGIN CATCH
        THROW;
    END CATCH
END;
