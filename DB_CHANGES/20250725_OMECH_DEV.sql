	   CASE WHEN SP.SLITTING_SRNO_FK = 0 THEN NULL ELSE SP.SLITTING_SRNO_FK END AS SLITTING_SRNO_FK,
	   --SP.SLITTING_SRNO_FK,
	   SP.IS_SLITTED,
	   ISNULL(SP.SLITTING_SCRAP,0) AS SLITTING_SCRAP,
	   ISNULL(SP.SLITTING_SCRAP_WEIGHT,0) AS SLITTING_SCRAP_WEIGHT,
	   SP.C_LOCATION AS SLITTING_SHIFT_TO_SRNO,
	   S.STATUS_NAME AS SLITTING_STATUS,
	   MV.VENDOR_NAME AS C_LOCATION
    FROM SLITTING_PROCESSES SP
