CREATE   PROCEDURE [dbo].[IU_STATUS_BY_SCHEDULE_DT_SRNO]
    @SCHEDULE_DT_SRNO NUMERIC
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE 
        @ITEM_TYPE VARCHAR(10),
        @ORDERED_QTY NUMERIC,
        @DISPATCHED_QTY NUMERIC,
        @REJECTED_QTY NUMERIC = 0,
        @HANDLED_QTY NUMERIC,
        @ORDERED_WEIGHT DECIMAL(18,2),
        @DISPATCHED_WEIGHT DECIMAL(18,2);

    -- Get ITEM_TYPE and base values from SCHEDULE_DETAIL + SCHEDULE_MASTER
    SELECT 
        @ORDERED_QTY = SD.QUANTITY,
        @DISPATCHED_QTY = ISNULL(SD.DISPATCHED_QTY, 0),
        @ORDERED_WEIGHT = ISNULL(SD.WEIGHT_KG, 0),
        @DISPATCHED_WEIGHT = ISNULL(SD.DISPATCHED_WEIGHT_KG, 0),
        @ITEM_TYPE = SM.ITEM_TYPE
    FROM 
        SCHEDULE_DETAIL SD
    INNER JOIN 
        SCHEDULE_MASTER SM ON SD.SCHEDULE_SRNO = SM.SCHEDULE_SRNO
    WHERE 
        SD.SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;

    IF @ITEM_TYPE = 'PIPE'
    BEGIN
        -- Get total rejected qty for this item
        SELECT 
            @REJECTED_QTY = ISNULL(SUM(REJECTED_QTY), 0)
        FROM 
            PO_ITEMS_REJECT
        WHERE 
            SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO AND DEL_FLAG = 0;

        SET @HANDLED_QTY = @DISPATCHED_QTY - @REJECTED_QTY;

        UPDATE SCHEDULE_DETAIL
        SET STATUS_SRNO = 
            CASE 
                WHEN @HANDLED_QTY >= @ORDERED_QTY THEN 12 -- Completed
                ELSE 11 -- Pending
            END
        WHERE SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;
    END
    ELSE IF @ITEM_TYPE IN ('SHEET', 'COIL')
    BEGIN
        UPDATE SCHEDULE_DETAIL
        SET STATUS_SRNO = 
            CASE 
                WHEN ISNULL(DISPATCHED_WEIGHT_KG, 0) >= ISNULL(WEIGHT_KG, 0) THEN 12 -- Completed
                ELSE 11 -- Pending
            END
        WHERE SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;
    END
END;
