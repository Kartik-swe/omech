    @GRADE_SRNO INT NULL,
    @THICNESS_SRNO INT NULL,
    @WIDTH DECIMAL NULL,
    @STATUS_SRNO INT NULL,
	@C_LOCATION INT NULL,
    @USER_SRNO INT NULL
AS
BEGIN
    SET NOCOUNT ON;

    -- Validate @MATERIAL_FLAG
    IF @MATERIAL_FLAG NOT IN ('A', 'M', 'P', 'S') 
    BEGIN
        THROW 50000, 'Invalid value for MATERIAL_FLAG.', 1;
    END;

    -- Create a temporary table for optimized storage
    CREATE TABLE #TempResult (
        MATERIAL_SRNO INT,
        SLITTING_SRNO INT,
        CHALLAN_NO NVARCHAR(15),
        GRADE NVARCHAR(10),
        THICKNESS DECIMAL(18,2),
        BALANCE_WIDTH DECIMAL(18,2),
        BALANCE_WEIGHT DECIMAL(18,2),
        STATUS_NAME NVARCHAR(50),
        C_LOCATION NVARCHAR(100),
        COIL_TYPE_FLAG NVARCHAR(50) NOT NULL
    );

    -- Fetch Mother Coil Data
    IF @MATERIAL_FLAG IN ('M', 'A') 
    BEGIN
        INSERT INTO #TempResult
        SELECT 
            RM.MATERIAL_SRNO,
			0 AS SLITTING_SRNO,
            RM.CHALLAN_NO,
            MG.GRADE,
            MT.THICKNESS,
            RM.MATERIAL_WIDTH - ISNULL(RM.SLITTED_WIDTH,0) - ISNULL(RM.MATERIAL_SCRAP, 0) AS BALANCE_WIDTH,
            ((RM.MATERIAL_WIDTH - ISNULL(RM.SLITTED_WIDTH,0) - ISNULL(RM.MATERIAL_SCRAP, 0)) / RM.MATERIAL_WIDTH) * RM.MATERIAL_WEIGHT AS BALANCE_WEIGHT,
            MS.STATUS_NAME, 
            MV.VENDOR_NAME AS C_LOCATION,
            'M' AS COIL_TYPE_FLAG
        FROM RAW_MATERIALS RM WITH (NOLOCK)
        INNER JOIN M_STATUS MS ON RM.MATERIAL_STATUS_SRNO = MS.STATUS_SRNO
        INNER JOIN M_VENDORS MV ON RM.C_LOCATION = MV.VENDOR_SRNO
        INNER JOIN M_GRADE MG ON RM.MATERIAL_GRADE_SRNO = MG.GRADE_SRNO
        INNER JOIN M_THICKNESS MT ON RM.MATERIAL_THICKNESS_SRNO = MT.THICKNESS_SRNO
        WHERE 
            (@F_DATE IS NULL OR RM.CREATED_AT >= @F_DATE) 
            AND (@TO_DATE IS NULL OR RM.CREATED_AT <= @TO_DATE)
            AND (@STATUS_SRNO IS NULL OR RM.MATERIAL_STATUS_SRNO = @STATUS_SRNO)
            AND (@WIDTH IS NULL OR RM.MATERIAL_WIDTH - ISNULL(RM.SLITTED_WIDTH,0) - ISNULL(RM.MATERIAL_SCRAP, 0) = @WIDTH)
            AND (@GRADE_SRNO IS NULL OR RM.MATERIAL_GRADE_SRNO = @GRADE_SRNO)
            AND (@THICNESS_SRNO IS NULL OR RM.MATERIAL_THICKNESS_SRNO = @THICNESS_SRNO)
            AND (@C_LOCATION IS NULL OR RM.C_LOCATION = @C_LOCATION)
			AND RM.MATERIAL_STATUS_SRNO IN(4,5,10)
			AND RM.DEL_FLAG = 0
    END; 

    -- Fetch Slitted & Semi-Slitted Coil Data
    IF @MATERIAL_FLAG IN ('S', 'P', 'A') 
    BEGIN
        INSERT INTO #TempResult
        SELECT 
            SP.MATERIAL_SRNO,
			SP.SLITTING_SRNO,
			RM.CHALLAN_NO,
            MG.GRADE,
            MT.THICKNESS,
            (SP.SLITTING_WIDTH - (ISNULL(SP.SLITTED_WIDTH,0))) AS BALANCE_WIDTH,
            ((SP.SLITTING_WIDTH - (ISNULL(SP.SLITTED_WIDTH,0)) - ISNULL(SP.SLITTING_SCRAP, 0)) / SP.SLITTING_WIDTH) * SP.SLITTING_WEIGHT AS BALANCE_WEIGHT,
            MS.STATUS_NAME, 
            MV.VENDOR_NAME AS C_LOCATION,
            CASE 
                WHEN SP.IS_SLITTED = 1 THEN 'S' 
                ELSE 'P' 
            END AS COIL_TYPE_FLAG
        FROM SLITTING_PROCESSES SP WITH (NOLOCK)
        INNER JOIN RAW_MATERIALS RM ON SP.MATERIAL_SRNO = RM.MATERIAL_SRNO
        INNER JOIN M_STATUS MS ON SP.STATUS_SRNO = MS.STATUS_SRNO
        INNER JOIN M_VENDORS MV ON SP.C_LOCATION = MV.VENDOR_SRNO
        INNER JOIN M_GRADE MG ON RM.MATERIAL_GRADE_SRNO = MG.GRADE_SRNO
        INNER JOIN M_THICKNESS MT ON RM.MATERIAL_THICKNESS_SRNO = MT.THICKNESS_SRNO
        WHERE 
            (@F_DATE IS NULL OR SP.CREATED_AT >= @F_DATE) 
            AND (@TO_DATE IS NULL OR SP.CREATED_AT <= @TO_DATE)
            AND (@STATUS_SRNO IS NULL OR SP.STATUS_SRNO = @STATUS_SRNO)
            AND (@WIDTH IS NULL OR (SP.SLITTING_WIDTH - (ISNULL(SP.SLITTED_WIDTH,0))) = @WIDTH)
            AND (@GRADE_SRNO IS NULL OR RM.MATERIAL_GRADE_SRNO = @GRADE_SRNO)
            AND (@THICNESS_SRNO IS NULL OR RM.MATERIAL_THICKNESS_SRNO = @THICNESS_SRNO)
			AND (@C_LOCATION IS NULL OR SP.C_LOCATION = @C_LOCATION)
			AND (@MATERIAL_FLAG IS NULL 
				OR (@MATERIAL_FLAG = 'S' AND SP.IS_SLITTED = 1) 
				OR (@MATERIAL_FLAG = 'P' AND SP.IS_SLITTED = 0)
				OR (@MATERIAL_FLAG = 'A' AND (SP.IS_SLITTED = 0 OR SP.IS_SLITTED = 1)))
			AND SP.STATUS_SRNO IN(4,5,10)
			AND SP.DEL_FLAG = 0
			AND RM.DEL_FLAG = 0
        
    END;

    -- Return final result
    SELECT CHALLAN_NO,C_LOCATION,BALANCE_WEIGHT,BALANCE_WIDTH,GRADE,THICKNESS,STATUS_NAME,COIL_TYPE_FLAG,
			STRING_AGG(SLITTING_SRNO, ',') AS SLITTING_SRNOS, -- Concatenate PKs
			STRING_AGG(MATERIAL_SRNO, ',') AS MATERIAL_SRNOS, -- Concatenate PKs
			CASE 
                WHEN (COIL_TYPE_FLAG = 'S' OR COIL_TYPE_FLAG = 'P' ) THEN COUNT(DISTINCT SLITTING_SRNO) 
                ELSE  COUNT(DISTINCT MATERIAL_SRNO)
            END AS QUANTITY,
			CASE 
                WHEN COIL_TYPE_FLAG = 'S' THEN 'Slitted Coil' 
				WHEN COIL_TYPE_FLAG = 'P' THEN 'Semi Slitted Coil' 
				ELSE 'Mother Coil'
            END AS COIL_TYPE
			--COUNT(DISTINCT MATERIAL_SRNO) AS QUANTITY,STRING_AGG(MATERIAL_SRNO, ', ') AS MATERIAL_SRNOS 
	FROM #TempResult
	GROUP BY C_LOCATION, BALANCE_WEIGHT, BALANCE_WIDTH,GRADE,THICKNESS,STATUS_NAME,COIL_TYPE_FLAG,CHALLAN_NO;--MATERIAL_SRNOS,SLITTING_SRNOS;

    -- Clear Temp Table
    TRUNCATE TABLE #TempResult;
END;
