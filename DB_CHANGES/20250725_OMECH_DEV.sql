CREATE   PROCEDURE [dbo].[DEL_M_GRADE]
    @GRADE_SRNO NUMERIC,  -- Primary Key of the grade to delete
    @USER_SRNO NUMERIC,    -- User performing the deletion
    @UT_SRNO NUMERIC    -- User performing the deletion
AS
BEGIN
    SET NOCOUNT ON;

	 -- Check if OD_SRNO is referenced in any other table
    IF EXISTS (SELECT 1 FROM RAW_MATERIALS WHERE MATERIAL_GRADE_SRNO = @GRADE_SRNO and DEL_FLAG = 0)
    BEGIN
        -- Prevent deletion if referenced
        THROW 50002, 'Cannot delete: Grade is being used in other records.', 1;
        RETURN;
    END

    -- Check if the record exists and is not already deleted
    IF EXISTS (SELECT 1 FROM M_GRADE WHERE GRADE_SRNO = @GRADE_SRNO AND DEL_FLAG = 0)
    BEGIN
        -- Soft delete the record
        UPDATE M_GRADE
        SET DEL_FLAG = 1,  -- Mark as deleted
            DEL_BY = @USER_SRNO,
            DEL_AT = GETDATE()
        WHERE GRADE_SRNO = @GRADE_SRNO;
        
        SELECT @GRADE_SRNO AS PK_SRNO;
    END
    ELSE
    BEGIN
		THROW 50001, 'Grade not found or already deleted.', 1;
    END
END;
GO
