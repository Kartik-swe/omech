CREATE   PROCEDURE [dbo].[IU_DISPATCH]
    @IU_FLAG CHAR(1),
    @SCHEDULE_SRNO INT,
    @SCHEDULE_DT_SRNO INT,
    @DISPATCH_QTY DECIMAL(10,2),
    @DC_NO NVARCHAR(50),
    @UT_SRNO INT,
    @USER_SRNO INT,
    @DISPATCH_SRNO INT = NULL OUTPUT -- NULL for insert, pass for update
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @STATUS INT;
        SELECT @STATUS = STATUS_SRNO 
        FROM SCHEDULE_DETAIL 
        WHERE SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;

        -- Block if request is closed
        IF @STATUS = 13
        BEGIN
            RAISERROR('This request is already closed.', 16, 1);
            ROLLBACK TRANSACTION;
            RETURN;
        END

        DECLARE 
            @ITEM_TYPE NVARCHAR(20),
            @OLD_DISPATCH_QTY DECIMAL(10,2) = 0;

        SELECT @ITEM_TYPE = ITEM_TYPE 
        FROM SCHEDULE_MASTER 
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO;

        IF @IU_FLAG = 'I'
        BEGIN
            -- Insert new dispatch
            INSERT INTO SCHEDULE_DISPATCH (
                SCHEDULE_SRNO,
                SCHEDULE_DT_SRNO,
                DISPATCH_QTY,
                DISPATCHED_WEIGHT_KG,
                DC_NO,
                DISPATCH_DATE,
                CREATED_AT,
                CREATED_BY,
                DEL_FLAG
            )
            VALUES (
                @SCHEDULE_SRNO,
                @SCHEDULE_DT_SRNO,
                CASE WHEN @ITEM_TYPE = 'PIPE' THEN @DISPATCH_QTY ELSE NULL END,
                CASE WHEN @ITEM_TYPE <> 'PIPE' THEN @DISPATCH_QTY ELSE NULL END,
                @DC_NO,
                GETDATE(),
                GETDATE(),
                @USER_SRNO,
                0
            );

            SET @DISPATCH_SRNO = SCOPE_IDENTITY();
        END
        ELSE
        BEGIN

            -- Update dispatch
            UPDATE SCHEDULE_DISPATCH
            SET 
                DISPATCH_QTY = CASE WHEN @ITEM_TYPE = 'PIPE' THEN @DISPATCH_QTY ELSE NULL END,
                DISPATCHED_WEIGHT_KG = CASE WHEN @ITEM_TYPE <> 'PIPE' THEN @DISPATCH_QTY ELSE NULL END,
                DC_NO = @DC_NO,
                MODIFIED_AT = GETDATE(),
                MODIFIED_BY = @USER_SRNO
            WHERE DISPATCH_SRNO = @DISPATCH_SRNO;
        END

        -- Update detail table using function
        IF @ITEM_TYPE = 'PIPE'
        BEGIN
            UPDATE SCHEDULE_DETAIL
            SET DISPATCHED_QTY = dbo.FN_CALCULATE_PO_DT_DISPATCHED_WT(@SCHEDULE_DT_SRNO),
                MODIFIED_AT = GETDATE(),
                MODIFIED_BY = CAST(@USER_SRNO AS NVARCHAR(100))
            WHERE SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;
        END
        ELSE
        BEGIN
            UPDATE SCHEDULE_DETAIL
            SET DISPATCHED_WEIGHT_KG = dbo.FN_CALCULATE_PO_DT_DISPATCHED_WT(@SCHEDULE_DT_SRNO),
                MODIFIED_AT = GETDATE(),
                MODIFIED_BY = CAST(@USER_SRNO AS NVARCHAR(100))
            WHERE SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO;
        END

        -- Update status
        EXEC IU_STATUS_BY_SCHEDULE_DT_SRNO @SCHEDULE_DT_SRNO;
        EXEC AUTO_SET_PO_MASTER_STATUS @SCHEDULE_SRNO;

        -- Return primary key
        SELECT @DISPATCH_SRNO AS PK;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
