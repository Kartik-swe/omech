CREATE   FUNCTION [dbo].[FN_GET_SLITTED_DATA] (
    @IS_MOTHER_COIL BIT,        -- Flag to determine which condition to use
    @SRNO INT  -- SLITTING_SRNO_FK parameter (optional, for when IsMother is 1)
)
RETURNS TABLE
AS
RETURN
(
    SELECT 
        ISNULL(SUM(SP.SLITTING_WIDTH), 0) AS SLITTED_WIDTH,
        ISNULL(SUM(SP.SLITTING_WEIGHT), 0) AS SLITTED_WEIGHT
    FROM SLITTING_PROCESSES SP
    WHERE SP.DEL_FLAG = 0
    AND (
        (@IS_MOTHER_COIL = 1 AND SP.MATERIAL_SRNO = @SRNO AND SP.SLITTING_LEVEL = 1) OR
        (@IS_MOTHER_COIL = 0 AND SP.SLITTING_SRNO_FK = @SRNO)
    )
)
