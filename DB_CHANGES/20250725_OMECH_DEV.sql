CREATE   PROCEDURE [dbo].[IU_M_GRADE]
    @IU_FLAG CHAR(1),      -- 'I' for Insert, 'U' for Update
    @GRADE NVARCHAR(10),   -- Grade value
    @UOM NVARCHAR(10) = NULL,     -- Unit of Measurement
    @USER_SRNO NUMERIC,    -- User serial number (for Created/Modified by)
    @UT_SRNO NUMERIC,    -- User serial number (for Created/Modified by)
    @GRADE_SRNO NUMERIC = NULL OUTPUT -- Return the Primary Key
AS
BEGIN
    SET NOCOUNT ON;

	-- Check for duplicate (same THICKNESS & UOM, considering NULL values)
    IF EXISTS (
        SELECT 1 FROM M_GRADE 
        WHERE GRADE = @GRADE
          AND ((UOM = @UOM) OR (UOM IS NULL AND @UOM IS NULL))  -- Handle NULL UOM case
          AND DEL_FLAG = 0 
          AND (@IU_FLAG = 'I' OR GRADE_SRNO <> GRADE_SRNO)
    )
    BEGIN
        RAISERROR ('Duplicate entry exists for the given Grade and UOM.', 16, 1);
        RETURN;
    END

    IF @IU_FLAG = 'I'
    BEGIN
        -- Insert new grade and return the new GRADE_SRNO
        INSERT INTO M_GRADE (GRADE, UOM, CREATED_BY, CREATED_AT)
        VALUES (@GRADE, @UOM, @USER_SRNO, GETDATE());

        -- Get the last inserted ID
        SET @GRADE_SRNO = SCOPE_IDENTITY();
    END
    ELSE IF @IU_FLAG = 'U'
    BEGIN
        -- Update existing grade
        UPDATE M_GRADE
        SET GRADE = @GRADE,
            UOM = @UOM,
            MODIFIED_BY = @USER_SRNO,
            MODIFIED_AT = GETDATE()
        WHERE GRADE_SRNO = @GRADE_SRNO AND DEL_FLAG = 0;

        

    END
    ELSE
    BEGIN
        PRINT 'Invalid IU_FLAG. Use "I" for Insert or "U" for Update';
        RETURN;
    END

	-- Return the updated primary key
        SELECT @GRADE_SRNO AS PK_SRNO
END;
