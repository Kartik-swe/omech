CREATE     PROCEDURE [dbo].[UPDATE_IS_SLITTED]
    @IU_FLAG CHAR(1),               -- 'I' for Insert, 'U' for Update
    @STATUS_FLAG CHAR(1),               -- 'I' for Insert, 'U' for Update
    @COIL_FLAG CHAR(1),               -- 'I' for Insert, 'U' for Update
    @USER_SRNO NUMERIC(18,0),        -- User identifier for tracking
    @SRNO NUMERIC(18,0) OUTPUT -- Output parameter to return primary key
AS
BEGIN
    BEGIN TRY
        -- Start transaction for consistency
        BEGIN TRANSACTION;

        -- Check if the operation is an Update
        IF @IU_FLAG = 'U'
        BEGIN
           
		 
            DECLARE @STATUS_SRNO INT = 0;
			--SELECT * FROM M_STATUS
            -- Assign Status_SRNO based on STATUS_FLAG  
            IF @STATUS_FLAG = 'C'  
                SET @STATUS_SRNO = 9;  
            ELSE IF @STATUS_FLAG = 'S'  
                SET @STATUS_SRNO = 8;  
            ELSE  
            BEGIN  
                RAISERROR ('Invalid STATUS_FLAG value. Use ''S'', or ''C''.', 16, 1);  
                RETURN;  
            END  

           
			
			 
			 -- Perform the update
			 IF @STATUS_FLAG = 'S'
			 BEGIN
				UPDATE SLITTING_PROCESSES
				SET 
					IS_SLITTED = 1,
					STATUS_SRNO = 8
				WHERE SLITTING_SRNO = @SRNO;
			END
			ELSE
			BEGIN
				 -- Update the respective table based on COIL_FLAG  
				DECLARE @SLITTED_WIDTH INT, @SLITTED_WEIGHT INT;
				IF @COIL_FLAG = 'M'  
				BEGIN  
					SELECT 
						@SLITTED_WIDTH = SLITTED_WIDTH,
						@SLITTED_WEIGHT = SLITTED_WEIGHT
					FROM dbo.FN_GET_SLITTED_DATA(1, @SRNO); 

					
					UPDATE RAW_MATERIALS  
					SET MATERIAL_STATUS_SRNO = @STATUS_SRNO,
						MATERIAL_SCRAP = MATERIAL_WIDTH - ISNULL(@SLITTED_WIDTH,0),
						MATERIAL_SCRAP_WEIGHT = MATERIAL_WEIGHT - ISNULL(@SLITTED_WEIGHT,0)
						--MODIFIED_BY = @USER_SRNO,  
						--MODIFIED_AT = GETDATE()  
					WHERE MATERIAL_SRNO = @SRNO;  
					
				END  
				ELSE  
				BEGIN 
					DECLARE @TEMP_MATERIAL_SRNO INT, @SCRAP_WIDTH INT , @SCRAP_WEIGHT INT
					SELECT 
						@SLITTED_WIDTH = SLITTED_WIDTH,
						@SLITTED_WEIGHT = SLITTED_WEIGHT
					FROM dbo.FN_GET_SLITTED_DATA(0, @SRNO); 



					UPDATE SLITTING_PROCESSES  
					SET STATUS_SRNO = @STATUS_SRNO,
						SLITTING_SCRAP = SLITTING_WIDTH - ISNULL(@SLITTED_WIDTH,0),
						SLITTING_SCRAP_WEIGHT = SLITTING_WEIGHT - ISNULL(@SLITTED_WEIGHT,0)
					   -- MODIFIED_BY = @USER_SRNO,  
						--MODIFIED_AT = GETDATE()  
					WHERE SLITTING_SRNO = @SRNO;  

					SELECT @TEMP_MATERIAL_SRNO = MATERIAL_SRNO,
							@SCRAP_WIDTH = SLITTING_SCRAP,
							@SCRAP_WEIGHT = SLITTING_SCRAP_WEIGHT
							FROM SLITTING_PROCESSES WHERE SLITTING_SRNO = @SRNO

					UPDATE RAW_MATERIALS  
					SET 
						SLIT_MATERIAL_SCRAP = ISNULL(SLIT_MATERIAL_SCRAP,0) + ISNULL(@SCRAP_WIDTH,0),
						SLIT_MATERIAL_SCRAP_WEIGHT = ISNULL(SLIT_MATERIAL_SCRAP_WEIGHT,0) + ISNULL(@SCRAP_WEIGHT,0)
					WHERE MATERIAL_SRNO = @TEMP_MATERIAL_SRNO;  
				END 
			END
			SELECT @SRNO AS SRNO , @STATUS_SRNO AS STATUS
        END  
        


        -- Commit the transaction
        COMMIT TRANSACTION;

		 -- Return the updated primary key
        SELECT @SRNO AS SLITTING_SRNO;
    END TRY
    BEGIN CATCH
        -- Rollback transaction in case of an error
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        -- Capture and re-throw the error
        DECLARE @ERROR_MESSAGE NVARCHAR(4000), @ERROR_SEVERITY INT, @ERROR_STATE INT;
        SELECT @ERROR_MESSAGE = ERROR_MESSAGE(), @ERROR_SEVERITY = ERROR_SEVERITY(), @ERROR_STATE = ERROR_STATE();
        RAISERROR (@ERROR_MESSAGE, @ERROR_SEVERITY, @ERROR_STATE);
    END CATCH
END;
