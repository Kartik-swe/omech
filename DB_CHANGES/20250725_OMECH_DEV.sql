@DT_REG_TO DATETIME NULL,
@SUPPLIER NVARCHAR(25) NULL,
@GRADE_SRNO NUMERIC NULL,
@THICKNESS_SRNO NUMERIC NULL,
@USER_SRNO NUMERIC,
@UT_SRNO NUMERIC
AS
BEGIN
    SET NOCOUNT ON;

	-- Fetch RAW MATERIALS
    DECLARE @RawMaterialTable TABLE (MATERIAL_SRNO NUMERIC);

    INSERT INTO @RawMaterialTable (MATERIAL_SRNO)
    SELECT RM.MATERIAL_SRNO
    FROM RAW_MATERIALS RM
    WHERE 
        RM.DEL_FLAG = 0 -- Only include active records
        AND RM.MATERIAL_STATUS_SRNO IN (4,5,8,9)
        AND (@CHALLAN_NO IS NULL OR RM.CHALLAN_NO LIKE '%' + @CHALLAN_NO + '%')
        AND (@SUPPLIER IS NULL OR RM.SUPPLIER LIKE '%' + @SUPPLIER + '%')
        AND (@DT_REG_FROM IS NULL OR RM.CREATED_AT >= @DT_REG_FROM) 
        AND (@DT_REG_TO IS NULL OR RM.CREATED_AT <= @DT_REG_TO)
        AND (@GRADE_SRNO IS NULL OR RM.MATERIAL_GRADE_SRNO = @GRADE_SRNO)
        AND (@THICKNESS_SRNO IS NULL OR RM.MATERIAL_THICKNESS_SRNO = @THICKNESS_SRNO);

    SELECT 
        RM.MATERIAL_SRNO,
        RM.CHALLAN_NO,
        RM.SUPPLIER,
        RM.MATERIAL_WIDTH,
        RM.MATERIAL_WEIGHT,
        ISNULL(RM.MATERIAL_SCRAP,0) AS MATERIAL_SCRAP,
        ISNULL(RM.MATERIAL_SCRAP_WEIGHT,0) AS MATERIAL_SCRAP_WEIGHT,
        ISNULL(RM.SLIT_MATERIAL_SCRAP,0) AS SLIT_MATERIAL_SCRAP,
        ISNULL(RM.SLIT_MATERIAL_SCRAP_WEIGHT,0) AS SLIT_MATERIAL_SCRAP_WEIGHT,
        RM.MATERIAL_GRADE_SRNO,
        RM.C_LOCATION AS MATERIAL_C_LOCATION_SRNO,
		RM.MATERIAL_THICKNESS_SRNO,
        ISNULL(RM.SLIT_MATERIAL_SCRAP,0) AS SLIT_MATERIAL_SCRAP,
        CONVERT(VARCHAR, RM.RECEIVED_DATE, 103) AS RECEIVED_DATE, -- Formatted date
        MV.VENDOR_NAME AS MATERIAL_C_LOCATION,
        G.GRADE AS MATERIAL_GRADE,
        T.THICKNESS AS MATERIAL_THICKNESS,
        S.STATUS_NAME AS MATERIAL_STATUS,
        RM.CREATED_AT,
        U.USERNAME
    FROM RAW_MATERIALS RM
    INNER JOIN M_VENDORS MV ON RM.C_LOCATION = MV.VENDOR_SRNO
    INNER JOIN M_GRADE G ON RM.MATERIAL_GRADE_SRNO = G.GRADE_SRNO
    INNER JOIN M_THICKNESS T ON RM.MATERIAL_THICKNESS_SRNO = T.THICKNESS_SRNO
    INNER JOIN M_STATUS S ON RM.MATERIAL_STATUS_SRNO = S.STATUS_SRNO
	INNER JOIN M_USER U ON RM.CREATED_BY = U.USER_SRNO
    wHERE RM.MATERIAL_SRNO IN (SELECT MATERIAL_SRNO FROM @RawMaterialTable)

    ORDER BY RM.CREATED_AT DESC; -- Order by creation date (latest first)

	SELECT 
		SP.MATERIAL_SRNO,
		SP.SLITTING_SRNO,
	   CONVERT(VARCHAR, SP.SLITTING_DATE, 103) AS SLITTING_DATE, -- Formatted date
	   sp.SLITTING_WIDTH,
	   ROUND(sp.SLITTING_WEIGHT,0) AS SLITTING_WEIGHT,
