    @IU_FLAG CHAR(1),         -- 'I' for Insert, 'U' for Update (currently not used, but reserved)
    @FLAG NVARCHAR(5),         -- 'ADD' or 'MINUS'
    @PR_INV_SRNO NUMERIC(18,0), -- Pipe Inventory Serial Number
    @PIPE_NOS NUMERIC(18,0),    -- Quantity to Add or Minus
    @UT_SRNO NUMERIC(18,0),     -- User Type Serial No (currently unused here)
    @USER_SRNO NUMERIC(18,0)    -- Logged in User Serial No
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @PR_SRNO NUMERIC(18,0);
        DECLARE @C_LOCATION NUMERIC(18,0);
        DECLARE @PIPE_TRN_TYPE_SRNO NUMERIC(18,0);

        -- Fetch related data
        SELECT 
            @PR_SRNO = PR_SRNO, 
            @C_LOCATION = C_LOCATION
        FROM PIPE_INVENTORY
        WHERE PR_INV_SRNO = @PR_INV_SRNO;

        IF @PR_SRNO IS NULL
        BEGIN
            -- Inventory record not found, raise error
            THROW 50001, 'Invalid PR_INV_SRNO. Inventory record not found.', 1;
        END

        -- Decide transaction type based on @FLAG
        IF @FLAG = 'ADD'
        BEGIN
            SET @PIPE_TRN_TYPE_SRNO = 1; -- 1 = ADD
            -- Update Inventory: Add quantity
            UPDATE PIPE_INVENTORY
            SET AVAILABLE_QUANTITY = ISNULL(AVAILABLE_QUANTITY, 0) + ISNULL(@PIPE_NOS,0)
            WHERE PR_INV_SRNO = @PR_INV_SRNO;
        END
        ELSE IF @FLAG = 'MINUS'
        BEGIN
            SET @PIPE_TRN_TYPE_SRNO = 5; -- 5 = MINUS
            -- Update Inventory: Subtract quantity
            UPDATE PIPE_INVENTORY
            SET AVAILABLE_QUANTITY = 
                CASE 
                    WHEN ISNULL(AVAILABLE_QUANTITY, 0) >= @PIPE_NOS THEN AVAILABLE_QUANTITY - @PIPE_NOS 
                    ELSE 0 -- prevent negative stock
                END
            WHERE PR_INV_SRNO = @PR_INV_SRNO;
        END
        ELSE
        BEGIN
            THROW 50002, 'Invalid FLAG value. Expected "ADD" or "MINUS".', 1;
        END

        -- Insert Transaction Log
        INSERT INTO PIPE_INVENTORY_LOG (
            PR_SRNO,
            C_LOCATION,
            QUANTITY,
            MACHINE_SRNO,
            MATERIAL_SRNO,
            SLITTING_SRNO,
            FROM_LOCATION,
            PIPE_TRN_TYPE_SRNO,
            TRN_DATE,
            TRN_BY,
            TRN_REMARK,
            IS_COIL_ENTRY,
            IS_COIL_COMPLETED,
            PG_SCRAP_WT,
            CREATED_BY,
            CREATED_AT
        )
        VALUES (
            @PR_SRNO,
            @C_LOCATION,
            @PIPE_NOS,
            NULL, NULL, NULL, NULL,
            @PIPE_TRN_TYPE_SRNO,
            GETDATE(),
            @USER_SRNO,
            NULL,
            0,
            NULL,
            NULL,
            @USER_SRNO,
            GETDATE()
        );

        COMMIT TRANSACTION;

        -- Return the PR_INV_SRNO
        SELECT @PR_INV_SRNO AS PR_INV_SRNO;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        -- Throw the error details
        THROW;
    END CATCH
END
