CREATE   PROCEDURE [dbo].[AUTO_SET_PO_MASTER_STATUS]
    @SCHEDULE_SRNO INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ITEM_TYPE VARCHAR(10);
    SELECT @ITEM_TYPE = ITEM_TYPE
    FROM SCHEDULE_MASTER
    WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;

    IF @ITEM_TYPE = 'PIPE'
    BEGIN
        DECLARE @T_TOTAL INT = 0,
                @T_CLOSED INT = 0,
                @T_COMPLETED_OR_CLOSED INT = 0;

        SELECT @T_TOTAL = COUNT(*) 
        FROM SCHEDULE_DETAIL 
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;

        SELECT @T_CLOSED = COUNT(*) 
        FROM SCHEDULE_DETAIL 
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0 AND STATUS_SRNO = 13;

        SELECT @T_COMPLETED_OR_CLOSED = COUNT(*) 
        FROM SCHEDULE_DETAIL 
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0 AND STATUS_SRNO IN (12, 13);

        IF @T_TOTAL = @T_CLOSED
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 13
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
        ELSE IF @T_TOTAL = @T_COMPLETED_OR_CLOSED
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 12
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
        ELSE
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 11
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
    END
    ELSE IF @ITEM_TYPE IN ('SHEET', 'COIL')
    BEGIN
        DECLARE 
            @TOTAL_LINES INT = 0,
            @COUNT_CLOSED INT = 0,
            @COUNT_COMPLETED INT = 0,
            @COUNT_PENDING INT = 0;

        SELECT 
            @TOTAL_LINES = COUNT(*),
            @COUNT_CLOSED = SUM(CASE WHEN STATUS_SRNO = 13 THEN 1 ELSE 0 END),
            @COUNT_COMPLETED = SUM(CASE WHEN STATUS_SRNO = 12 THEN 1 ELSE 0 END),
            @COUNT_PENDING = SUM(CASE WHEN STATUS_SRNO = 11 THEN 1 ELSE 0 END)
        FROM SCHEDULE_DETAIL
        WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;

        IF @TOTAL_LINES = 0
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 11
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
        ELSE IF @COUNT_CLOSED = @TOTAL_LINES
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 13 -- All Closed
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
        ELSE IF @COUNT_PENDING = 0 AND (@COUNT_COMPLETED + @COUNT_CLOSED = @TOTAL_LINES)
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 12 -- All Completed or Closed
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
        ELSE
        BEGIN
            UPDATE SCHEDULE_MASTER
            SET STATUS_SRNO = 11 -- At least one pending
            WHERE SCHEDULE_SRNO = @SCHEDULE_SRNO AND DEL_FLAG = 0;
        END
    END
END;
GO
