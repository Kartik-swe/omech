CREATE   PROCEDURE [dbo].[IU_PIPE_SHIFT_LOCATION]
    @IU_FLAG CHAR(1),
    @PR_INV_SRNO NUMERIC(18,0),
    @PR_SRNO NUMERIC(18,0),
    @FROM_LOCATION NUMERIC(18,0),
    @TO_LOCATION NUMERIC(18,0),
    @PIPE_NOS NUMERIC(18,0),
    @TRN_DATE DATETIME NULL,
    @TRN_BY NUMERIC(18,0),
    @TRN_REMARK NVARCHAR(100),
    @USER_SRNO NUMERIC(18,0)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        -- Start a transaction
        BEGIN TRANSACTION

        DECLARE @PIPE_TRN_TYPE_SRNO NUMERIC(18,0) = 2;
		SET @TRN_DATE = GETDATE();
	SET @TRN_BY = @USER_SRNO;
        -- Reduce quantity from the source location
        UPDATE PIPE_INVENTORY
        SET AVAILABLE_QUANTITY = AVAILABLE_QUANTITY - @PIPE_NOS
        WHERE PR_INV_SRNO = @PR_INV_SRNO
          AND PR_SRNO = @PR_SRNO
          AND C_LOCATION = @FROM_LOCATION
          AND AVAILABLE_QUANTITY >= @PIPE_NOS;

        -- Check if there was enough quantity to reduce, else raise an error
        IF @@ROWCOUNT = 0
        BEGIN
            THROW 50001, 'Insufficient quantity in source location.', 1;
        END

        -- Add quantity to the new location
        IF EXISTS (SELECT 1 FROM PIPE_INVENTORY WHERE PR_SRNO = @PR_SRNO AND C_LOCATION = @TO_LOCATION)
        BEGIN
            UPDATE PIPE_INVENTORY
            SET AVAILABLE_QUANTITY = AVAILABLE_QUANTITY + @PIPE_NOS
            WHERE PR_SRNO = @PR_SRNO 
              AND C_LOCATION = @TO_LOCATION;
        END
        ELSE
        BEGIN
            INSERT INTO PIPE_INVENTORY (PR_SRNO, C_LOCATION, AVAILABLE_QUANTITY, CREATED_AT, CREATED_BY)
            VALUES (@PR_SRNO, @TO_LOCATION, @PIPE_NOS, GETDATE(), @USER_SRNO);
        END

        -- Insert into PIPE_INVENTORY_LOG
        INSERT INTO PIPE_INVENTORY_LOG (PR_SRNO, C_LOCATION, QUANTITY, MACHINE_SRNO, MATERIAL_SRNO, SLITTING_SRNO, 
                                        FROM_LOCATION, PIPE_TRN_TYPE_SRNO, TRN_DATE, TRN_BY, TRN_REMARK,
                                        IS_COIL_ENTRY, IS_COIL_COMPLETED, PG_SCRAP_WT, CREATED_BY, CREATED_AT)
        VALUES (@PR_SRNO, @TO_LOCATION, @PIPE_NOS, NULL, NULL, NULL, 
                @FROM_LOCATION, @PIPE_TRN_TYPE_SRNO, @TRN_DATE, @TRN_BY, @TRN_REMARK,
                0, NULL, NULL, @USER_SRNO, GETDATE());

        -- Commit transaction
        COMMIT TRANSACTION;
		SELECT @PR_INV_SRNO AS PR_INV_SRNO;

    END TRY
    BEGIN CATCH
        -- Rollback transaction in case of error
        ROLLBACK TRANSACTION;

        -- Throw the error message
        THROW;
    END CATCH
END;
