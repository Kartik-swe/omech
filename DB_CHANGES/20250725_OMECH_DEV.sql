        );

		-- ✅ Automatically update master status based on detail statuses
    EXEC AUTO_SET_PO_MASTER_STATUS @SCHEDULE_SRNO = @SCHEDULE_SRNO;

    SELECT @SCHEDULE_SRNO AS SCHEDULE_SRNO 
