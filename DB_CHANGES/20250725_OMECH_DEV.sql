    ;WITH CTE_SCHEDULE_SRNO AS (
        SELECT TRY_CAST(TRIM(value) AS INT) AS SCHEDULE_SRNO
        FROM STRING_SPLIT(@SCHEDULE_SRNOS, ',')
        WHERE TRY_CAST(TRIM(value) AS INT) IS NOT NULL
