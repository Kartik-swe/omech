CREATE   PROCEDURE [dbo].[IU_PIPES]
    @IU_FLAG CHAR(1),  -- 'I' for Insert, 'U' for Update
    @MATERIAL_SRNO INT,
    @SLITTING_SRNO INT = NULL,
    @MACHINE_SRNO INT,
    @OD_SRNO INT,
    @WORK_SHIFT_SRNO INT = NULL,
    @C_LOCATION INT,
    @IS_COIL_COMPLETED BIT = NULL,
    @P_LENGTH VARCHAR(50),
    @PIPE_NOS INT,  -- Number of pipes
    @PG_SCRAP_WT DECIMAL(18,2) = NULL,
    @P_WEIGHT DECIMAL(18,2) = NULL,
    @REMARKS VARCHAR(255) = NULL,
    @PG_DONE_AT DATETIME,
    @UT_SRNO INT,
    @USER_SRNO INT,
    @PG_SRNO INT = NULL OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @PIPE_NAME VARCHAR(200), @THICKNESS VARCHAR(50), @GRADE VARCHAR(50), @OD VARCHAR(50);
    DECLARE @PRE_LOG_STATUS_SRNO NUMERIC(18,0);
    DECLARE @COUNTER INT = 1;

    -- Fetch thickness, grade, and OD
    SELECT 
        @THICKNESS = MT.THICKNESS,
        @GRADE = MG.GRADE,
        @PRE_LOG_STATUS_SRNO = 
            CASE 
                WHEN @SLITTING_SRNO > 0 THEN (SELECT STATUS_SRNO FROM SLITTING_PROCESSES WHERE SLITTING_SRNO = @SLITTING_SRNO)
                ELSE RM.MATERIAL_STATUS_SRNO
            END
    FROM RAW_MATERIALS RM
    INNER JOIN M_GRADE MG ON RM.MATERIAL_GRADE_SRNO = MG.GRADE_SRNO
    INNER JOIN M_THICKNESS MT ON RM.MATERIAL_THICKNESS_SRNO = MT.THICKNESS_SRNO
    WHERE RM.MATERIAL_SRNO = @MATERIAL_SRNO;

    SELECT @OD = MO.OD FROM M_OD MO WHERE MO.OD_SRNO = @OD_SRNO;

    -- Construct Pipe Name
    SET @PIPE_NAME = CONCAT('OD: ', @OD, 'mm, Thickness: ', @THICKNESS, 'mm, Grade: ', @GRADE);

    IF @IU_FLAG = 'I'  
    BEGIN
        -- Insert into PIPE_GROUP
        DECLARE @PG_TABLE TABLE (PG_SRNO INT);
        INSERT INTO PIPE_GROUP (
            MATERIAL_SRNO, SLITTING_SRNO, MACHINE_SRNO, OD_SRNO, WORK_SHIFT_SRNO,
            PG_SCRAP_WT, PG_DONE_BY, PG_DONE_AT, DEL_FLAG, CREATED_BY, CREATED_AT
        )
        OUTPUT INSERTED.PG_SRNO INTO @PG_TABLE
        VALUES (
            @MATERIAL_SRNO, @SLITTING_SRNO, @MACHINE_SRNO, @OD_SRNO, @WORK_SHIFT_SRNO,
            @PG_SCRAP_WT, @USER_SRNO, @PG_DONE_AT, 0, @USER_SRNO, GETDATE()
        );
        SELECT @PG_SRNO = PG_SRNO FROM @PG_TABLE;
    END  
    ELSE IF @IU_FLAG = 'U'  
    BEGIN
        -- Update PIPE_GROUP
        UPDATE PIPE_GROUP
        SET 
            MATERIAL_SRNO = @MATERIAL_SRNO,
            SLITTING_SRNO = @SLITTING_SRNO,
            MACHINE_SRNO = @MACHINE_SRNO,
            OD_SRNO = @OD_SRNO,
            WORK_SHIFT_SRNO = @WORK_SHIFT_SRNO,
            PG_SCRAP_WT = @PG_SCRAP_WT,
            PG_DONE_BY = @USER_SRNO,
            PG_DONE_AT = @PG_DONE_AT,
            MODIFIED_BY = @USER_SRNO,
            MODIFIED_AT = GETDATE()
        WHERE PG_SRNO = @PG_SRNO;

        -- Soft delete old pipes
        UPDATE PIPE_DT 
        SET DEL_FLAG = 1, DEL_BY = @USER_SRNO, DEL_AT = GETDATE()
        WHERE PG_SRNO = @PG_SRNO;
    END

    -- Insert Pipes into PIPE_DT
    WHILE @COUNTER <= @PIPE_NOS
    BEGIN
        INSERT INTO PIPE_DT (
            PG_SRNO, PIPE_NAME, P_LENGTH, P_WEIGHT, C_LOCATION, 
            DEL_FLAG, CREATED_BY, CREATED_AT
        )
        VALUES (
            @PG_SRNO, @PIPE_NAME, @P_LENGTH, @P_WEIGHT, @C_LOCATION, 
            0, @USER_SRNO, GETDATE()
        );
        SET @COUNTER = @COUNTER + 1;
    END;

    -- Handle Coil Completion
    IF @IS_COIL_COMPLETED = 1
    BEGIN
        IF @SLITTING_SRNO > 0
            UPDATE SLITTING_PROCESSES
            SET STATUS_SRNO = 10 -- Shifted to production
            WHERE SLITTING_SRNO = @SLITTING_SRNO;
        ELSE
            UPDATE RAW_MATERIALS
            SET MATERIAL_STATUS_SRNO = 10 -- Shifted to production
            WHERE MATERIAL_SRNO = @MATERIAL_SRNO;
        
        -- Log status change
        EXEC IU_STATUS_LOG @MATERIAL_SRNO, @SLITTING_SRNO, @PRE_LOG_STATUS_SRNO, NULL, NULL, @PG_DONE_AT, @USER_SRNO, @UT_SRNO, 0;
    END;

    SELECT @PG_SRNO AS PG_SRNO;
END;
