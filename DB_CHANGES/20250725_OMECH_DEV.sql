		CASE WHEN SM.ITEM_TYPE = 'PIPE' THEN SDISP.DISPATCH_QTY ELSE SDISP.DISPATCHED_WEIGHT_KG END AS DISPATCH_QTY

	FROM  SCHEDULE_MASTER SM
	INNER JOIN SCHEDULE_DETAIL SD ON SD.SCHEDULE_SRNO = SM.SCHEDULE_SRNO
	INNER JOIN SCHEDULE_DISPATCH SDISP ON SDISP.SCHEDULE_DT_SRNO = SD.SCHEDULE_DT_SRNO
	WHERE SM.SCHEDULE_SRNO = @SCHEDULE_SRNO




