	LEFT OUTER JOIN M_STATUS S ON SP.STATUS_SRNO = S.STATUS_SRNO
    WHERE SP.DEL_FLAG = 0 -- Only include active records
	AND SP.MATERIAL_SRNO IN (SELECT MATERIAL_SRNO FROM @RawMaterialTable)
    ORDER BY SP.CREATED_AT DESC, SP.SLITTING_SRNO DESC; -- Order by creation date (latest first)
