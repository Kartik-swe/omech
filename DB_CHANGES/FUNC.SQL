CREATE   FUNCTION [dbo].[FN_GET_SLITTED_WIDTH] (
    @IS_MOTHER_COIL BIT,        -- Flag to determine which condition to use
    @SRNO INT  -- SLITTING_SRNO_FK parameter (optional, for when IsMother is 1)
)
RETURNS INT
AS
BEGIN
    DECLARE @SLITTED_WIDTH INT;

    IF @IS_MOTHER_COIL = 0 --SLOITTING PROCESSES
    BEGIN
        -- Handle condition for SLITTING_SRNO_FK
        SELECT @SLITTED_WIDTH = ISNULL((
            SELECT SUM(SLITTING_WIDTH)
            FROM SLITTING_PROCESSES
            WHERE DEL_FLAG = 0
            AND SLITTING_SRNO_FK = @SRNO
        ), 0)
    END
    ELSE IF @IS_MOTHER_COIL = 1 -- MOTHER COIL
    BEGIN
        -- Handle condition for MATERIAL_SRNO
        SELECT @SLITTED_WIDTH = ISNULL((
            SELECT SUM(SLITTING_WIDTH)
            FROM SLITTING_PROCESSES
            WHERE DEL_FLAG = 0
            AND MATERIAL_SRNO = @SRNO
			AND SLITTING_LEVEL = 1
        ), 0)
    END

    RETURN @SLITTED_WIDTH
END
GO
