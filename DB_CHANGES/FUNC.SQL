CREATE   FUNCTION [dbo].[FN_CALCULATE_PIPE_WEIGHT_BY_SRNO] (
    @OD_SRNO INT,
    @THICKNESS_SRNO INT,
    @GRADE_SRNO INT,
    @LENGTH NUMERIC(10, 2),
    @QUANTITY INT
)
RETURNS DECIMAL(18, 4)
AS
BEGIN
    DECLARE 
        @OD NUMERIC(10, 2),
        @THICKNESS NUMERIC(10, 2),
        @DENSITY NUMERIC(10, 4),
        @SINGLE_WEIGHT DECIMAL(18, 4),
        @TOTAL_WEIGHT DECIMAL(18, 4);

    -- Get values from master tables
    SELECT @OD = OD FROM M_OD WHERE OD_SRNO = @OD_SRNO AND DEL_FLAG = 0;
    SELECT @THICKNESS = THICKNESS FROM M_THICKNESS WHERE THICKNESS_SRNO = @THICKNESS_SRNO AND DEL_FLAG = 0;
    SELECT @DENSITY = DENSITY FROM M_GRADE WHERE GRADE_SRNO = @GRADE_SRNO AND DEL_FLAG = 0;

    -- Fallbacks
    IF @DENSITY IS NULL SET @DENSITY = 7.93; -- Default to SS304
    IF @OD IS NULL OR @THICKNESS IS NULL RETURN 0;

    -- Calculate single pipe weight
    SET @SINGLE_WEIGHT = 
        (@OD - @THICKNESS) * @THICKNESS * @LENGTH * @DENSITY * 0.001;

    -- Total weight
    SET @TOTAL_WEIGHT = @SINGLE_WEIGHT * @QUANTITY;

    RETURN @TOTAL_WEIGHT;
END;
GO
