CREATE   FUNCTION [dbo].[FN_UPDATE_MATERIAL_STATUS] (
    @IS_MOTHER_COIL BIT,        -- Flag to determine which condition to use
    @SRNO INT  -- SLITTING_SRNO/ MATERIAL_SRNO
)
RETURNS INT
AS
BEGIN
    DECLARE @MATERIAL_WIDTH INT, 
            @SLITTED_WIDTH INT, 
            @MATERIAL_SCRAP INT = 0, 
            @STATUS_SRNO INT = 0;

    SET @SLITTED_WIDTH = dbo.FN_GET_SLITTED_WIDTH(@IS_MOTHER_COIL,@SRNO)
    
    IF @IS_MOTHER_COIL = 1
    BEGIN
        SELECT @MATERIAL_WIDTH = MATERIAL_WIDTH, 
               @MATERIAL_SCRAP = MATERIAL_SCRAP  -- Fetch scrap value as well
        FROM RAW_MATERIALS 
        WHERE MATERIAL_SRNO = @SRNO AND DEL_FLAG = 0
    END
    ELSE 
    BEGIN
        SELECT @MATERIAL_WIDTH = SLITTING_WIDTH, 
               @MATERIAL_SCRAP = SLITTING_SCRAP  -- Fetch scrap value as well
        FROM SLITTING_PROCESSES 
        WHERE SLITTING_SRNO = @SRNO AND DEL_FLAG = 0
    END

    -- Ensure @MATERIAL_SCRAP is not NULL
    SET @MATERIAL_SCRAP = ISNULL(@MATERIAL_SCRAP, 0)

    IF @SLITTED_WIDTH = 0 
        SET @STATUS_SRNO = 4 -- NEW
    ELSE IF @SLITTED_WIDTH = @MATERIAL_WIDTH - @MATERIAL_SCRAP
        SET @STATUS_SRNO = 9 -- COMPLETED
    ELSE 
        SET @STATUS_SRNO = 5 -- IN SLITTING


    RETURN @STATUS_SRNO
END
GO
