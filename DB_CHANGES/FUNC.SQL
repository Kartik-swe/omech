CREATE   FUNCTION [dbo].[FN_CALCULATE_PO_DT_DISPATCHED_WT] (
    @SCHEDULE_DT_SRNO INT
)
RETURNS DECIMAL(18, 2)
AS
BEGIN
    RETURN (
        SELECT ISNULL(SUM(
            CASE 
                WHEN M.ITEM_TYPE = 'PIPE' THEN D.DISPATCH_QTY
                ELSE D.DISPATCHED_WEIGHT_KG
            END
        ), 0)
        FROM SCHEDULE_DISPATCH D
        INNER JOIN SCHEDULE_DETAIL SD ON D.SCHEDULE_DT_SRNO = SD.SCHEDULE_DT_SRNO
        INNER JOIN SCHEDULE_MASTER M ON SD.SCHEDULE_SRNO = M.SCHEDULE_SRNO
        WHERE D.SCHEDULE_DT_SRNO = @SCHEDULE_DT_SRNO
    );
END
